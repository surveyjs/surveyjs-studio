export interface ActionEntry {
  /** The old action's name, as its route has it. */
  action: string;
  controller: Controller;
  methods: HTTPMethods[];
  /**
   * Paths under each of the controller's prefixes, with a `/:id` form where the old route has one;
   * `""` is the prefix itself.
   */
  paths: string[];
  key: KeyRule;
  /**
   * Where the key is read (`withKeyRule`): by default bound from a form body, then the query, for a
   * `text` action, and from the query for the others; `query` where the old action read it there.
   */
  keyFrom?: KeySource;
  /**
   * `read` when every operation the action calls is a `GET` in Studio's contract and the action
   * takes no method but GET, HEAD or OPTIONS; else `write` (so a `GET` that makes a key,
   * `generateAccessKey`, and a `PUT` that calls only `GET`s are writes). The replay sends only reads.
   */
  effect: "read" | "write";
  /** The contract operations (operationIds) the action calls. */
  studio: readonly string[];
  handler: RouteHandlerMethod;
  /** The largest body (bytes; default: the old host's limit), or the setting that gives it. */
  bodyLimit?: number | ((settings: BridgeSettings) => number);
  /** Runs before the body is read (e.g. to refuse a request without reading it). */
  onRequest?: onRequestAsyncHookHandler;
  /** Runs once the body has been read, before the handler. */
  preHandler?: preHandlerAsyncHookHandler;
}

